@dataclass(frozen=True)
class QualityResult:
    score: int
    total: int
    checks: tuple[tuple[str, bool], ...]


def _normalized(text: str) -> str:
    return re.sub(r"[\s\u00a0]+", "", text).upper().replace("Ё", "Е")


def evaluate_answer(answer: str) -> QualityResult:
    normalized = _normalized(answer)
    checks = (
        ("проект", "ORBITA-7429" in normalized),
        ("актуальная дата", "26.10.2026" in normalized and "18.10.2026" not in normalized),
        ("актуальный бюджет", "510000" in normalized and "450000" not in normalized),
        ("актуальный подрядчик", "МЕРИДИАН" in normalized and "АТЛАС" not in normalized),
        ("открытый вопрос", "КЕЙТЕРИНГ" in normalized),
    )
    return QualityResult(
        score=sum(passed for _, passed in checks),
        total=len(checks),
        checks=checks,
    )
