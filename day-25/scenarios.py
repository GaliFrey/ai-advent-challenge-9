"""Two 12-turn scripts; checkpoints are visible to the evaluator only."""
import copy
from memory import empty_state


def script(identity, title, rows):
    state = empty_state()
    turns = []
    for number, (question, resolved, changes) in enumerate(rows, 1):
        for field, texts in changes.items():
            state[field] = [{'text': text, 'turn': number, 'quote': question} for text in texts]
        turns.append({'question': question, 'resolved': resolved, 'expected_state': copy.deepcopy(state)})
    return {'id': identity, 'title': title, 'turns': turns}


